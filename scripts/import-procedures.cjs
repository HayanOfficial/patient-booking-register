#!/usr/bin/env node
// ==============================================================================
// scripts/import-procedures.cjs
// One-time script: reads Surgical_Procedures_List.xlsx and generates
// supabase/seed_procedures.sql  (safe to run multiple times — ON CONFLICT DO NOTHING)
// ==============================================================================
'use strict';
const XLSX = require('xlsx');
const fs   = require('fs');
const path = require('path');

const FILE  = path.join(__dirname, '..', 'reference', 'Surgical_Procedures_List.xlsx');
const OUT   = path.join(__dirname, '..', 'supabase', 'seed_procedures.sql');

console.log('Reading:', FILE);

const wb = XLSX.readFile(FILE);
const ws = wb.Sheets['Procedure List'];
if (!ws) {
  console.error('Sheet "Procedure List" not found. Sheets available:', wb.SheetNames.join(', '));
  process.exit(1);
}

const rows = XLSX.utils.sheet_to_json(ws, { header: 1, defval: '' });
// Header row is index 4: ["No.", "Category", "Procedure / recorded entry", "Entry type", "Clarification"]
// Data rows start at index 5

const procedures = [];
const seen = new Set();

rows.slice(5).forEach((row, i) => {
  const cat   = String(row[1] ?? '').trim();
  const name  = String(row[2] ?? '').trim();
  if (!name) return;
  const key = name.toLowerCase();
  if (seen.has(key)) {
    console.warn(`  ⚠️  Duplicate skipped (row ${i + 6}): "${name}"`);
    return;
  }
  seen.add(key);
  procedures.push({ category: cat || null, name, sort_order: procedures.length + 1 });
});

console.log(`\n✅ Extracted ${procedures.length} unique procedures:\n`);
procedures.forEach(p => console.log(`  ${p.sort_order}. [${p.category || 'Other'}] ${p.name}`));

// --- Generate SQL ---
function esc(s) {
  if (s === null || s === undefined) return 'NULL';
  return "'" + String(s).replace(/'/g, "''") + "'";
}

const lines = [
  '-- ============================================================',
  '-- seed_procedures.sql',
  '-- Generated by scripts/import-procedures.cjs from Surgical_Procedures_List.xlsx',
  '-- Safe to run multiple times: ON CONFLICT (lower(name)) DO NOTHING',
  '-- ============================================================',
  '',
  '-- Ensure unique index on lower(name) exists',
  'CREATE UNIQUE INDEX IF NOT EXISTS procedures_lower_name_uniq ON public.procedures (lower(name));',
  '',
  'INSERT INTO public.procedures (name, category, active, sort_order)',
  'VALUES',
  ...procedures.map((p, i) =>
    `  (${esc(p.name)}, ${esc(p.category)}, true, ${p.sort_order})${i < procedures.length - 1 ? ',' : ''}`
  ),
  'ON CONFLICT (lower(name)) DO NOTHING;',
  '',
  `-- Total: ${procedures.length} procedures`,
  `-- Generated: ${new Date().toISOString()}`,
];

fs.writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log(`\n✅ SQL seed written to: ${OUT}`);
console.log('\nNext: paste the contents of supabase/seed_procedures.sql into Supabase SQL Editor and run it.');
